from pathlib import Path
import sys

# -------------------------------------------------------------------
# Add the project root to Python's module search path.
# -------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parents[2]

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from dotenv import load_dotenv
# from langchain.retrievers.multi_query import MultiQueryRetriever
from langchain_classic.retrievers.multi_query import MultiQueryRetriever
from langchain_community.document_loaders import TextLoader
from langchain_community.vectorstores import FAISS
from langchain_google_genai import GoogleGenerativeAIEmbeddings
from langchain_text_splitters import RecursiveCharacterTextSplitter

from llm_client import get_llm
from utils.helpers import print_separator, print_title

load_dotenv()


def main() -> None:
    print_title("Multi Query Retriever")

    file_path = PROJECT_ROOT / "data" / "input" / "similarity.txt"
    loader = TextLoader(file_path)
    documents = loader.load()

    splitter = RecursiveCharacterTextSplitter(
        chunk_size=200,
        chunk_overlap=50,
    )

    chunks = splitter.split_documents(documents)

    embeddings = GoogleGenerativeAIEmbeddings(
        model="gemini-embedding-001"
    )

    vector_store = FAISS.from_documents(
        chunks,
        embeddings,
    )

    # MultiQueryRetriever is a LangChain retriever that uses an LLM to generate multiple variations of a user's query.
    # Why?
    # Sometimes users ask questions differently from how information is written in your documents.
    retriever = MultiQueryRetriever.from_llm(
        retriever=vector_store.as_retriever(search_kwargs={"k": 2}),
        llm=get_llm(),

        # This tells MultiQueryRetriever to include the original user query along with the generated variations.
        # That way, retrieval considers both:
        # - The user's original question.
        # - The alternative questions generated by Gemini.
        include_original=True,
    )

    query = "I can't log into my account."
    documents = retriever.invoke(query)

    print(f"Query:\n{query}")

    print_separator()


    print(f"Retrieved {len(documents)} Documents\n")

    print_separator()

    for index, document in enumerate(documents, start=1):

        print(f"Document {index}\n")

        print(document.page_content)

        print_separator()


if __name__ == "__main__":
    main()


# =============================================================================
# Concept Summary
#
# MultiQueryRetriever improves retrieval by generating multiple versions
# of the user's question using an LLM.
#
# Instead of relying on a single search query, it searches using several
# semantically related queries and combines the retrieved results.
#
# This often improves recall in RAG systems.
# =============================================================================