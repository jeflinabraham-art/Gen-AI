"""
Description
-----------
Demonstrates a Sequential Chain using the LangChain Expression Language (LCEL).

The output of one step becomes the input of the next step, allowing us
to build multi-step LLM workflows.
"""

from pathlib import Path
import sys

# -------------------------------------------------------------------
# Add the project root to Python's module search path.
# -------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parents[2]

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

# StrOutputParser extracts the generated text as a Python string.
from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import PromptTemplate

from llm_client import get_llm
from utils.helpers import print_separator, print_title


def main() -> None:
    print_title("Sequential Chain: Interview Preparation")

    llm = get_llm()

    # Step 1: Generate an interview question

    # .from_template(): LangChain automatically identifies {role} as an input variable. You dont have to explicitly mention it through input_variables=[""]
    question_prompt = PromptTemplate.from_template(
        """
        Generate ONE beginner-friendly technical interview
        question for a {role} position.

        Return only the question.
        """
    )

    # The pipe operator | connects components so that the output of one component flows into the next.
    # 1. question_prompt: Takes the role and formats the instructions.
    # 2. llm: Reads the instructions and generates a question.
    # 3. StrOutputParser(): Extracts the generated text as a Python string.

    # The variable question_chain now represents this connected sequence of operations. Creating the chain does not itself generate a question, the chain executes when you invoke it.
    question_chain = question_prompt | llm | StrOutputParser()

    # Step 2: Generate an answer to the question

    # This template has two input variables:
    # - {role} — the candidate's job role.
    # - {question} — the question generated by Chain 1.
    answer_prompt = PromptTemplate.from_template(
        """
        You are helping a candidate prepare for an interview.

        Job Role: {role}

        Interview Question:
        {question}

        Provide a beginner-friendly answer with a simple example.
        """
    )

    answer_chain = answer_prompt | llm | StrOutputParser()

    role = "Java Backend Developer"
    print(f"Job Role: {role}")
    print_separator()

    # Execute Step 1
    # invoke() executes the chain with the input you supply.
    question = question_chain.invoke({"role": role})
    print("Interview Question:")
    print(question)
    print_separator()

    # Execute Step 2 using Step 1's output
    answer = answer_chain.invoke({
        "role": role,
        "question": question
    })

    print("Model Answer:")
    print(answer)
    print_separator()


if __name__ == "__main__":
    main()
